export const projectEffectEntityOperationRealization = Effect.fn(
  "projectEffectEntityOperationRealization",
)(function* (
  document: CheckedCoreDocument,
  stateMachineId: string,
  realizationId: string,
): Effect.fn.Return<string, TargetProjectionError> {
  const realization = document.declarations.find(
    (declaration): declaration is OperationRealizationDeclaration =>
      declaration.kind === "operationRealization" && declaration.id === realizationId,
  );
  if (realization === undefined) {
    return yield* targetProjectionFailure(
      "missing-declaration",
      `operationRealization:${realizationId}`,
      `Effect entity projection cannot resolve checked realization ${realizationId}`,
    );
  }
  if (realization.operation.stateMachine !== stateMachineId) {
    return yield* targetProjectionFailure(
      "inconsistent-declaration",
      `operationRealization:${realization.id}.stateMachine:${realization.operation.stateMachine}`,
      `Effect entity projection realization ${realization.id} targets ${realization.operation.stateMachine}, not ${stateMachineId}`,
    );
  }

  const machine = document.declarations.find(
    (declaration): declaration is StateMachineDeclaration =>
      declaration.kind === "stateMachine" && declaration.id === stateMachineId,
  );
  if (machine === undefined) {
    return yield* targetProjectionFailure(
      "missing-declaration",
      `stateMachine:${stateMachineId}`,
      `Effect entity projection cannot resolve checked state machine ${stateMachineId}`,
    );
  }
  const operation = machine.transitions.find(({ id }) => id === realization.operation.operation);
  if (operation === undefined) {
    return yield* targetProjectionFailure(
      "inconsistent-declaration",
      `operationRealization:${realization.id}.transition:${machine.id}.${realization.operation.operation}`,
      `Effect entity projection cannot resolve checked transition ${machine.id}.${realization.operation.operation}`,
    );
  }
  if (machine.initializers.length !== 1) {
    return yield* targetProjectionFailure(
      "unsupported-target",
      `stateMachine:${machine.id}.initializers`,
      `Effect entity projection requires exactly one initializer in ${machine.id}`,
    );
  }
  const initializer = machine.initializers[0];
  if (initializer === undefined || initializer.parameters.length !== machine.state.fields.length) {
    return yield* targetProjectionFailure(
      "unsupported-target",
      `stateMachine:${machine.id}.${initializer?.id ?? "initializer"}`,
      `Effect entity projection requires initializer inputs to match ${machine.state.id} fields`,
    );
  }
  if (operation.parameters.length === 0) {
    return yield* targetProjectionFailure(
      "unsupported-target",
      `stateMachine:${machine.id}.${operation.id}`,
      `Effect entity projection requires a message operation parameter`,
    );
  }

  try {
    const source = yield* projectEffectOperationRealization(document, realizationId);
    return emitEffectEntityOperationRealization(
      source,
      machine,
      operation,
      initializer,
      realization,
    );
  } catch (error) {
    return yield* targetProjectionFailure(
      "unsupported-target",
      `operationRealization:${realization.id}`,
      thrownMessage(error),
    );
  }
});

