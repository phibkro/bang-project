const projectType = (reference: string): string => {
  switch (reference) {
    case "String":
      return "string";
    case "Integer":
      return "bigint";
    default:
      return "never";
  }
};

const projectIntegerLiteral = (value: string): string => `${value}n`;
const projectStringArray = (values: ReadonlyArray<string>): string =>
  `[${values.map((value) => JSON.stringify(value)).join(", ")}]`;
const lowerFirst = (value: string): string => `${value[0]?.toLowerCase() ?? ""}${value.slice(1)}`;
const upperFirst = (value: string): string => `${value[0]?.toUpperCase() ?? ""}${value.slice(1)}`;

const projectEffectTerm = (term: Term): string => {
  if (term.kind === "variable") return term.id;
  return `realization.${term.operation}(${term.arguments.map(projectEffectTerm).join(", ")})`;
};

export const projectEffectRefinement = (refinement: RefinementDeclaration): string => {
  if (refinement.base !== "Integer") {
    throw new TypeError(
      `Effect projection does not support ${refinement.id} over ${refinement.base}`,
    );
  }

  const minimum = projectIntegerLiteral(refinement.predicate.right.value);
  const constructor = `make${refinement.id}`;

  return `// Generated by BANG M001. Do not edit.\nimport { Order, Schema } from "effect";\n\nconst isGreaterThanOrEqualTo = Schema.makeIsGreaterThanOrEqualTo({ order: Order.BigInt });\n\nexport const ${refinement.id} = Schema.BigInt.check(isGreaterThanOrEqualTo(${minimum})).pipe(\n  Schema.brand("${refinement.id}"),\n);\nexport type ${refinement.id} = typeof ${refinement.id}.Type;\n\nexport const ${constructor} = (input: bigint): ${refinement.id} => ${refinement.id}.make(input);\n`;
};

export const projectEffectFiniteModel = (
  theory: TheoryDeclaration,
  model: FiniteModelDeclaration,
): string => {
  if (model.theory !== theory.id) {
    throw new TypeError(`model ${model.id} does not interpret theory ${theory.id}`);
  }

  const carriers = model.carriers
    .map(
      ({ sort, elements }) =>
        `export const ${sort} = Schema.Literals(${projectStringArray(elements)});\nexport type ${sort} = typeof ${sort}.Type;`,
    )
    .join("\n\n");
  const operations = theory.operations
    .map((operation) => {
      const parameters = operation.parameters.map(({ id, sort }) => `${id}: ${sort}`).join(", ");
      return `  readonly ${operation.id}: (${parameters}) => ${operation.result};`;
    })
    .join("\n");
  const cases = model.operations
    .map(({ operation, rows }) => {
      const projectedRows = rows
        .map(
          (row) =>
            `    { arguments: ${projectStringArray(row.arguments)}, result: ${JSON.stringify(row.result)} },`,
        )
        .join("\n");
      return `  ${operation}: [\n${projectedRows}\n  ],`;
    })
    .join("\n");

  return `// Generated by BANG M002. Do not edit.\nimport { Schema } from "effect";\n\n${carriers}\n\nexport interface ${theory.id}Model {\n${operations}\n}\n\nexport const ${model.id}Cases = {\n${cases}\n} as const;\n`;
};

export const projectEffectPropertySuite = (theory: TheoryDeclaration): string => {
  const sortSchemas = new Map<string, string>();
  for (const sort of theory.sorts) {
    if (sort.representation?.type !== "Integer") {
      throw new TypeError(
        `Effect property projection requires Integer representation for sort ${theory.id}.${sort.id}`,
      );
    }
    sortSchemas.set(sort.id, "Schema.BigInt");
  }
  if (theory.laws.length === 0) {
    throw new TypeError(`Effect property projection requires at least one law in ${theory.id}`);
  }

  const carriers = theory.sorts
    .map(
      ({ id }) =>
        `export const ${id} = ${sortSchemas.get(id)};\nexport type ${id} = typeof ${id}.Type;\nconst ${id}Arbitrary = Schema.toArbitrary(${id})(FastCheck);`,
    )
    .join("\n");
  const operations = theory.operations
    .map((operation) => {
      const parameters = operation.parameters.map(({ id, sort }) => `${id}: ${sort}`).join(", ");
      return `  readonly ${operation.id}: (${parameters}) => ${operation.result};`;
    })
    .join("\n");

  const predicates = theory.laws
    .map((law) => {
      if (law.parameters.length === 0) {
        throw new TypeError(
          `Effect property projection does not support nullary law ${theory.id}.${law.id}`,
        );
      }
      const parameters = law.parameters.map(({ id }) => id).join(", ");
      const left = projectEffectTerm(law.proposition.left);
      const right = projectEffectTerm(law.proposition.right);
      return `const ${law.id}Holds = (realization: ${theory.id}Model, ${law.parameters.map(({ id, sort }) => `${id}: ${sort}`).join(", ")}): boolean =>\n  ${left} === ${right};\n\nconst ${law.id}Property = (realization: ${theory.id}Model) =>\n  FastCheck.property(${law.parameters.map(({ sort }) => `${sort}Arbitrary`).join(", ")}, (${law.parameters.map(({ id, sort }) => `${id}: ${sort}`).join(", ")}) => ${law.id}Holds(realization, ${parameters}));`;
    })
    .join("\n\n");
  const registrations = theory.laws
    .map((law) => {
      const schemas = law.parameters.map(({ sort }) => sort).join(", ");
      const parameters = law.parameters.map(({ id }) => id).join(", ");
      return `  it.effect.prop(\n    "${theory.id}.${law.id}",\n    [${schemas}] as const,\n    ([${parameters}]) =>\n      Effect.sync(() => {\n        expect(${law.id}Holds(realization, ${parameters})).toBe(true);\n      }),\n    { fastCheck: { seed: options.seed, numRuns: options.numRuns } },\n  );`;
    })
    .join("\n\n");
  const checks = theory.laws
    .map(
      (law) =>
        `  const ${law.id}Details = FastCheck.check(${law.id}Property(realization), {\n    seed: options.seed,\n    numRuns: options.numRuns,\n  });`,
    )
    .join("\n\n");
  const results = theory.laws
    .map(
      (law) => `    {
      law: "${law.id}",
      passed: !${law.id}Details.failed,
      requestedCases: options.numRuns,
      executedRuns: ${law.id}Details.numRuns,
      seed: ${law.id}Details.seed,
      numShrinks: ${law.id}Details.numShrinks,
      counterexamplePath: ${law.id}Details.counterexamplePath,
      counterexample:
        ${law.id}Details.counterexample === null
          ? null
          : ${law.id}Details.counterexample.map((value) => String(value)),
    },`,
    )
    .join("\n");

  return `// Generated by BANG M003. Do not edit.\nimport { expect, it } from "@effect/vitest";\nimport { Effect, Schema } from "effect";\nimport { FastCheck } from "effect/testing";\n\n${carriers}\n\nexport interface ${theory.id}Model {\n${operations}\n}\n\nexport interface PropertySuiteOptions {\n  readonly seed: number;\n  readonly numRuns: number;\n}\n\nexport interface PropertyLawResult {\n  readonly law: string;\n  readonly passed: boolean;\n  readonly requestedCases: number;\n  readonly executedRuns: number;\n  readonly seed: number;\n  readonly numShrinks: number;\n  readonly counterexamplePath: string | null;\n  readonly counterexample: ReadonlyArray<string> | null;\n}\n\n${predicates}\n\nexport const register${theory.id}Properties = (\n  realization: ${theory.id}Model,\n  options: PropertySuiteOptions,\n): void => {\n${registrations}\n};\n\nexport const check${theory.id}Properties = (\n  realization: ${theory.id}Model,\n  options: PropertySuiteOptions,\n): ReadonlyArray<PropertyLawResult> => {\n${checks}\n\n  return [\n${results}\n  ];\n};\n`;
};

const projectEffectBridgeTerm = (
  term: BridgeTerm,
  variables: ReadonlyMap<string, string> = new Map(),
): string => {
  if (term.kind === "variable") return variables.get(term.id) ?? term.id;
  return `${term.operation.participant}.${term.operation.operation}(${term.arguments
    .map((argument) => projectEffectBridgeTerm(argument, variables))
    .join(", ")})`;
};

export class TargetProjectionError extends Schema.TaggedError<TargetProjectionError>()(
  "TargetProjectionError",
  { message: Schema.String },
) {}

const dataTypeContainsReference = (type: DataType, declarationId: string): boolean => {
  switch (type.kind) {
    case "builtin":
      return false;
    case "reference":
      return type.id === declarationId;
    case "list":
      return dataTypeContainsReference(type.element, declarationId);
    case "record":
      return type.fields.some((field) => dataTypeContainsReference(field.type, declarationId));
  }
};

const projectEffectDataType = (type: DataType): string => {
  switch (type.kind) {
    case "builtin":
      return type.name;
    case "reference":
      return type.id;
    case "list":
      return `ReadonlyArray<${projectEffectDataType(type.element)}>`;
    case "record":
      return `{ ${type.fields
        .map(
          (field) => `readonly ${JSON.stringify(field.id)}: ${projectEffectDataType(field.type)}`,
        )
        .join("; ")} }`;
  }
};

const projectEffectDataSchema = (type: DataType, declarationId: string): string => {
  switch (type.kind) {
    case "builtin":
      return type.name;
    case "reference":
      return type.id === declarationId ? `${declarationId}Reference` : type.id;
    case "list":
      return `Schema.Array(${projectEffectDataSchema(type.element, declarationId)})`;
    case "record":
      return `Schema.Struct({ ${type.fields
        .map(
          (field) =>
            `${JSON.stringify(field.id)}: ${projectEffectDataSchema(field.type, declarationId)}`,
        )
        .join(", ")} })`;
  }
};

const firstDataLeafPath = (type: DataType, prefix: string): string => {
  switch (type.kind) {
    case "builtin":
    case "reference":
      return prefix;
    case "list":
      return prefix;
    case "record": {
      const field = type.fields[0];
      return field === undefined ? prefix : firstDataLeafPath(field.type, `${prefix}.${field.id}`);
    }
  }
};

const projectRecursiveDataPath = (
  type: DataType,
  declarationId: string,
  valueExpression: string,
  pathExpression: string,
  depth = 0,
): string => {
  switch (type.kind) {
    case "reference":
      return `return ${declarationId}DomainPath(${valueExpression}, ${pathExpression});`;
    case "list": {
      const child = `recursiveChild${depth}`;
      return `if (${valueExpression}.length === 0) return ${pathExpression};
      const ${child} = ${valueExpression}[0];
      if (${child} === undefined) return ${pathExpression};
      ${projectRecursiveDataPath(
        type.element,
        declarationId,
        child,
        `\`\${${pathExpression}}[0]\``,
        depth + 1,
      )}`;
    }
    case "record": {
      const field = type.fields.find((candidate) =>
        dataTypeContainsReference(candidate.type, declarationId),
      );
      if (field === undefined) return `return ${pathExpression};`;
      return projectRecursiveDataPath(
        field.type,
        declarationId,
        `${valueExpression}[${JSON.stringify(field.id)}]`,
        `\`\${${pathExpression}}.${field.id}\``,
        depth,
      );
    }
    case "builtin":
      return `return ${pathExpression};`;
  }
};

const projectDataDomainPathCases = (declaration: DataDeclaration): string =>
  declaration.constructors
    .map((constructor) => {
      const base = `\`\${prefix}.${upperFirst(constructor.tag)}\``;
      const recursiveField = constructor.fields.find((field) =>
        dataTypeContainsReference(field.type, declaration.id),
      );
      const valueName = recursiveField === undefined ? "_candidate" : "candidate";
      const body =
        recursiveField === undefined
          ? `return \`\${base}.${
              constructor.fields[0] === undefined
                ? declaration.discriminator
                : firstDataLeafPath(constructor.fields[0].type, constructor.fields[0].id)
            }\`;`
          : projectRecursiveDataPath(
              recursiveField.type,
              declaration.id,
              `${valueName}[${JSON.stringify(recursiveField.id)}]`,
              `\`\${base}.${recursiveField.id}\``,
            );
      return `    Match.when({ ${JSON.stringify(declaration.discriminator)}: ${JSON.stringify(constructor.tag)} }, (${valueName}) => {
      const base = ${base};
      ${body}
    }),`;
    })
    .join("\n");

export const projectEffectData = Effect.fn("projectEffectData")(function* (
  document: CheckedCoreDocument,
  declarationId: string,
): Effect.fn.Return<string, TargetProjectionError> {
  const declaration = document.declarations.find(
    (candidate): candidate is DataDeclaration =>
      candidate.kind === "data" && candidate.id === declarationId,
  );
  if (declaration === undefined) {
    return yield* new TargetProjectionError({
      message: `Effect data projection cannot resolve checked data ${declarationId}`,
    });
  }
  for (const constructor of declaration.constructors) {
    const references: Array<string> = [];
    const collectReferences = (type: DataType): void => {
      if (type.kind === "reference") references.push(type.id);
      if (type.kind === "list") collectReferences(type.element);
      if (type.kind === "record") {
        for (const field of type.fields) collectReferences(field.type);
      }
    };
    for (const field of constructor.fields) collectReferences(field.type);
    const externalReference = references.find((reference) => reference !== declaration.id);
    if (externalReference !== undefined) {
      return yield* new TargetProjectionError({
        message: `Effect data projection does not yet bundle external data ${externalReference} referenced by ${declaration.id}.${constructor.tag}`,
      });
    }
  }

  const variants = declaration.constructors.map(
    (constructor, index) => `${declaration.id}Constructor${index}`,
  );
  const interfaces = declaration.constructors
    .map((constructor, index) => {
      const fields = constructor.fields
        .map(
          (field) =>
            `  readonly ${JSON.stringify(field.id)}: ${projectEffectDataType(field.type)};`,
        )
        .join("\n");
      return `/** Core source: data ${declaration.id} constructor ${constructor.tag}. */
export interface ${variants[index]} {
  readonly ${JSON.stringify(declaration.discriminator)}: ${JSON.stringify(constructor.tag)};
${fields}
}`;
    })
    .join("\n\n");
  const schemas = declaration.constructors
    .map((constructor, index) => {
      const fields = constructor.fields
        .map(
          (field) =>
            `  ${JSON.stringify(field.id)}: ${projectEffectDataSchema(field.type, declaration.id)},`,
        )
        .join("\n");
      return `export const ${variants[index]}: Schema.Codec<${variants[index]}> = Schema.Struct({
  ${JSON.stringify(declaration.discriminator)}: Schema.Literal(${JSON.stringify(constructor.tag)}),
${fields}
});`;
    })
    .join("\n\n");

  return `// Generated by BANG M005A. Do not edit.
import { expect, it } from "@effect/vitest";
import { Effect, Match, Result, Schema } from "effect";
import { FastCheck } from "effect/testing";

export const Identifier = Schema.String.pipe(
  Schema.check(Schema.isPattern(/^[A-Za-z][A-Za-z0-9]*$/)),
);
export type Identifier = typeof Identifier.Type;

${interfaces}

export type ${declaration.id} = ${variants.join(" | ")};

const ${declaration.id}Reference = Schema.suspend(
  (): Schema.Codec<${declaration.id}> => ${declaration.id},
);

${schemas}

export const ${declaration.id}: Schema.Codec<${declaration.id}> = Schema.Union([
  ${variants.join(",\n  ")},
]);

export interface ${declaration.id}Decoder {
  readonly decode: (input: unknown) => Effect.Effect<${declaration.id}, unknown>;
}

export interface DecoderPropertyResult {
  readonly passed: boolean;
  readonly requestedCases: number;
  readonly executedRuns: number;
  readonly seed: number;
  readonly numShrinks: number;
  readonly counterexamplePath: string | null;
}

export interface ${declaration.id}ConformanceResult {
  readonly valid: DecoderPropertyResult;
  readonly invalid: DecoderPropertyResult;
  readonly maximumObservedDepth: number;
}

const ${declaration.id}Arbitrary = Schema.toArbitrary(${declaration.id})(FastCheck);

const dataDepth = (value: unknown): number => {
  if (Array.isArray(value)) {
    return value.length === 0 ? 0 : 1 + Math.max(...value.map(dataDepth));
  }
  if (typeof value !== "object" || value === null) return 0;
  return 1 + Math.max(0, ...Object.values(value).map(dataDepth));
};

const ${declaration.id}DomainPath = (
  value: ${declaration.id},
  prefix = ${JSON.stringify(declaration.id)},
): string =>
  Match.value(value).pipe(
${projectDataDomainPathCases(declaration)}
    Match.exhaustive,
  );

const preservesValue = (left: unknown, right: unknown): boolean =>
  JSON.stringify(left) === JSON.stringify(right);

const invalidMutation = (value: ${declaration.id}): unknown => ({
  ...value,
  [${JSON.stringify(declaration.discriminator)}]: "__invalid__",
});

export const check${declaration.id}Decoder = (
  decoder: ${declaration.id}Decoder,
  options: { readonly seed: number; readonly numRuns: number },
): ${declaration.id}ConformanceResult => {
  let maximumObservedDepth = 0;
  let validCounterexample: ${declaration.id} | null = null;
  const validProperty = FastCheck.property(${declaration.id}Arbitrary, (value) => {
    maximumObservedDepth = Math.max(maximumObservedDepth, dataDepth(value));
    const decoded = Effect.runSync(Effect.result(decoder.decode(value)));
    const passed = Result.isSuccess(decoded) && preservesValue(decoded.success, value);
    if (!passed) validCounterexample = value;
    return passed;
  });
  const valid = FastCheck.check(validProperty, options);

  const invalidProperty = FastCheck.property(${declaration.id}Arbitrary, (value) => {
    const decoded = Effect.runSync(Effect.result(decoder.decode(invalidMutation(value))));
    return Result.isFailure(decoded);
  });
  const invalid = FastCheck.check(invalidProperty, options);

  return {
    valid: {
      passed: !valid.failed,
      requestedCases: options.numRuns,
      executedRuns: valid.numRuns,
      seed: valid.seed,
      numShrinks: valid.numShrinks,
      counterexamplePath:
        validCounterexample === null ? null : ${declaration.id}DomainPath(validCounterexample),
    },
    invalid: {
      passed: !invalid.failed,
      requestedCases: options.numRuns,
      executedRuns: invalid.numRuns,
      seed: invalid.seed,
      numShrinks: invalid.numShrinks,
      counterexamplePath: invalid.failed ? ${JSON.stringify(declaration.id)} : null,
    },
    maximumObservedDepth,
  };
};

export const register${declaration.id}DecoderConformance = (
  decoder: ${declaration.id}Decoder,
  options: { readonly seed: number; readonly numRuns: number },
): void => {
  it.effect("${declaration.id} decoder accepts and preserves generated valid values", () =>
    Effect.sync(() => {
      const result = check${declaration.id}Decoder(decoder, options);
      expect(result.valid.passed).toBe(true);
    }),
  );
  it.effect("${declaration.id} decoder rejects generated invalid mutations", () =>
    Effect.sync(() => {
      const result = check${declaration.id}Decoder(decoder, options);
      expect(result.invalid.passed).toBe(true);
    }),
  );
};
`;
});

export const projectEffectTheoryBridge = Effect.fn("projectEffectTheoryBridge")(function* (
  document: CheckedCoreDocument,
  bridgeId: string,
): Effect.fn.Return<string, TargetProjectionError> {
  const bridge = document.declarations.find(
    (declaration): declaration is TheoryBridgeDeclaration =>
      declaration.kind === "theoryBridge" && declaration.id === bridgeId,
  );
  if (bridge === undefined) {
    return yield* new TargetProjectionError({
      message: `Effect bridge projection cannot resolve checked bridge ${bridgeId}`,
    });
  }
  const theories = document.declarations.filter(
    (declaration): declaration is TheoryDeclaration => declaration.kind === "theory",
  );
  if (bridge.participants.length !== 2) {
    return yield* new TargetProjectionError({
      message: `Effect bridge projection requires exactly two participants in ${bridge.id}`,
    });
  }
  if (bridge.laws.length === 0) {
    return yield* new TargetProjectionError({
      message: `Effect bridge projection requires at least one law in ${bridge.id}`,
    });
  }

  const theoryById = new Map(theories.map((theory) => [theory.id, theory]));
  const participantTheories = new Map<string, TheoryDeclaration>();
  for (const participant of bridge.participants) {
    const theory = theoryById.get(participant.theory);
    if (theory === undefined) {
      return yield* new TargetProjectionError({
        message: `Effect bridge projection cannot resolve participant ${participant.id}:${participant.theory}`,
      });
    }
    participantTheories.set(participant.id, theory);
  }

  for (const sharedSort of bridge.sharedSorts) {
    for (const member of sharedSort.members) {
      const theory = participantTheories.get(member.participant);
      const sort = theory?.sorts.find(({ id }) => id === member.sort);
      if (sort?.representation?.type !== "Integer") {
        return yield* new TargetProjectionError({
          message: `Effect bridge projection requires Integer representation for shared sort ${bridge.id}.${sharedSort.id} member ${member.participant}.${member.sort}`,
        });
      }
    }
  }

  const sharedSortFor = Effect.fn("projectEffectTheoryBridge.sharedSortFor")(function* (
    participant: string,
    sort: string,
  ): Effect.fn.Return<string, TargetProjectionError> {
    const shared = bridge.sharedSorts.find((candidate) =>
      candidate.members.some(
        (member) => member.participant === participant && member.sort === sort,
      ),
    );
    if (shared === undefined) {
      return yield* new TargetProjectionError({
        message: `Effect bridge projection cannot project unshared sort ${participant}.${sort}`,
      });
    }
    return shared.id;
  });

  const generatedSorts = HashSet.fromIterable(
    bridge.laws.flatMap((law) => law.parameters.map(({ sort }) => sort)),
  );
  const carriers = bridge.sharedSorts
    .map(({ id }) => {
      const arbitrary = HashSet.has(generatedSorts, id)
        ? `\nconst ${id}Arbitrary = Schema.toArbitrary(${id})(FastCheck);`
        : "";
      return `export const ${id} = Schema.BigInt;\nexport type ${id} = typeof ${id}.Type;${arbitrary}`;
    })
    .join("\n");

  const modelDeclarations = new Array<string>();
  for (const participant of bridge.participants) {
    const theory = participantTheories.get(participant.id);
    if (theory === undefined) {
      return yield* new TargetProjectionError({
        message: `Effect bridge projection lost checked participant ${participant.id}`,
      });
    }
    const operationDeclarations = new Array<string>();
    for (const operation of theory.operations) {
      const parameterDeclarations = new Array<string>();
      for (const parameter of operation.parameters) {
        const sort = yield* sharedSortFor(participant.id, parameter.sort);
        parameterDeclarations.push(`${parameter.id}: ${sort}`);
      }
      const result = yield* sharedSortFor(participant.id, operation.result);
      operationDeclarations.push(
        `  readonly ${operation.id}: (${parameterDeclarations.join(", ")}) => ${result};`,
      );
    }
    modelDeclarations.push(
      `export interface ${theory.id}Model {\n${operationDeclarations.join("\n")}\n}`,
    );
  }
  const models = modelDeclarations.join("\n\n");

  const realizationParameters = bridge.participants
    .map((participant) => `${participant.id}: ${participant.theory}Model`)
    .join(", ");
  const realizationArguments = bridge.participants.map(({ id }) => id).join(", ");
  const participantIdentities = projectStringArray(
    bridge.participants.map(({ id, theory }) => `${id}:${theory}`),
  );

  const predicateDeclarations = new Array<string>();
  for (const law of bridge.laws) {
    if (law.parameters.length === 0) {
      return yield* new TargetProjectionError({
        message: `Effect bridge projection does not support nullary law ${bridge.id}.${law.id}`,
      });
    }
    const parameters = law.parameters.map(({ id, sort }) => `${id}: ${sort}`).join(", ");
    const parameterArguments = law.parameters.map(({ id }) => id).join(", ");
    const left = projectEffectBridgeTerm(law.proposition.left);
    const right = projectEffectBridgeTerm(law.proposition.right);
    predicateDeclarations.push(
      `const ${law.id}Holds = (${realizationParameters}, ${parameters}): boolean =>\n  ${left} === ${right};\n\nconst ${law.id}Property = (${realizationParameters}) =>\n  FastCheck.property(${law.parameters.map(({ sort }) => `${sort}Arbitrary`).join(", ")}, (${parameters}) => ${law.id}Holds(${realizationArguments}, ${parameterArguments}));`,
    );
  }
  const predicates = predicateDeclarations.join("\n\n");

  const registrations = bridge.laws
    .map((law) => {
      const schemas = law.parameters.map(({ sort }) => sort).join(", ");
      const parameters = law.parameters.map(({ id }) => id).join(", ");
      return `  it.effect.prop(
    "${bridge.id}.${law.id}",
    [${schemas}] as const,
    ([${parameters}]) =>
      Effect.sync(() => {
        expect(${law.id}Holds(${realizationArguments}, ${parameters})).toBe(true);
      }),
    { fastCheck: { seed: options.seed, numRuns: options.numRuns } },
  );`;
    })
    .join("\n\n");

  const checks = bridge.laws
    .map(
      (law) =>
        `  const ${law.id}Details = FastCheck.check(${law.id}Property(${realizationArguments}), {\n    seed: options.seed,\n    numRuns: options.numRuns,\n  });\n  const ${law.id}Counterexample = ${law.id}Details.counterexample;`,
    )
    .join("\n\n");

  const results = bridge.laws
    .map((law) => {
      const counterexampleVariables = new Map(
        law.parameters.map(({ id }, index) => [id, `${law.id}Counterexample[${index}]`]),
      );
      const assignments = law.parameters
        .map(
          ({ id }, index) =>
            `          { parameter: "${id}", value: String(${law.id}Counterexample[${index}]) },`,
        )
        .join("\n");
      const left = projectEffectBridgeTerm(law.proposition.left, counterexampleVariables);
      const right = projectEffectBridgeTerm(law.proposition.right, counterexampleVariables);
      return `    {
      obligation: "${bridge.id}.${law.id}",
      bridge: "${bridge.id}",
      law: "${law.id}",
      participants: ${participantIdentities},
      passed: !${law.id}Details.failed,
      requestedCases: options.numRuns,
      executedRuns: ${law.id}Details.numRuns,
      numSkips: ${law.id}Details.numSkips,
      seed: ${law.id}Details.seed,
      numShrinks: ${law.id}Details.numShrinks,
      counterexamplePath: ${law.id}Details.counterexamplePath,
      counterexample:
        ${law.id}Counterexample === null
          ? null
          : {
              assignment: [
${assignments}
              ],
              leftObservation: String(${left}),
              rightObservation: String(${right}),
            },
    },`;
    })
    .join("\n");

  return `// Generated by BANG M005. Do not edit.\nimport { expect, it } from "@effect/vitest";\nimport { Effect, Schema } from "effect";\nimport { FastCheck } from "effect/testing";\n\n${carriers}\n\n${models}\n\nexport interface BridgeSuiteOptions {\n  readonly seed: number;\n  readonly numRuns: number;\n}\n\nexport interface BridgeCounterexample {\n  readonly assignment: ReadonlyArray<{ readonly parameter: string; readonly value: string }>;\n  readonly leftObservation: string;\n  readonly rightObservation: string;\n}\n\nexport interface BridgeLawResult {\n  readonly obligation: string;\n  readonly bridge: string;\n  readonly law: string;\n  readonly participants: ReadonlyArray<string>;\n  readonly passed: boolean;\n  readonly requestedCases: number;\n  readonly executedRuns: number;\n  readonly numSkips: number;\n  readonly seed: number;\n  readonly numShrinks: number;\n  readonly counterexamplePath: string | null;\n  readonly counterexample: BridgeCounterexample | null;\n}\n\n${predicates}\n\nexport const register${bridge.id}Properties = (\n  ${realizationParameters},\n  options: BridgeSuiteOptions,\n): void => {\n${registrations}\n};\n\nexport const check${bridge.id}Properties = (\n  ${realizationParameters},\n  options: BridgeSuiteOptions,\n): ReadonlyArray<BridgeLawResult> => {\n${checks}\n\n  return [\n${results}\n  ];\n};\n`;
});

const projectStateValue = (value: StateValue, state: string): string => {
  switch (value.kind) {
    case "parameter":
      return value.id;
    case "stateField":
      return `${state}.${value.field}`;
    case "integerLiteral":
      return projectIntegerLiteral(value.value);
  }
};

const projectStatePredicate = (predicate: StatePredicate, state: string): string =>
  `${projectStateValue(predicate.left, state)} >= ${projectStateValue(predicate.right, state)}`;

export const projectEffectStateMachine = (machine: StateMachineDeclaration): string => {
  for (const field of machine.state.fields) {
    if (field.type !== "Integer") {
      throw new TypeError(
        `Effect state-machine projection requires Integer field ${machine.id}.${field.id}`,
      );
    }
  }
  for (const operation of [...machine.initializers, ...machine.transitions]) {
    for (const parameter of operation.parameters) {
      if (parameter.type !== "Integer") {
        throw new TypeError(
          `Effect state-machine projection requires Integer parameter ${machine.id}.${operation.id}.${parameter.id}`,
        );
      }
    }
  }
  if (machine.invariants.length === 0) {
    throw new TypeError(
      `Effect state-machine projection requires at least one invariant in ${machine.id}`,
    );
  }

  const fields = machine.state.fields.map(({ id }) => `  ${id}: Schema.BigInt,`).join("\n");
  const modelInitializers = machine.initializers
    .map((operation) => {
      const parameters = operation.parameters.map(({ id }) => `${id}: bigint`).join(", ");
      return `  readonly ${operation.id}: (${parameters}) => ${machine.state.id};`;
    })
    .join("\n");
  const modelTransitions = machine.transitions
    .map((operation) => {
      const parameters = operation.parameters.map(({ id }) => `${id}: bigint`).join(", ");
      const separator = parameters.length === 0 ? "" : `, ${parameters}`;
      return `  readonly ${operation.id}: (state: ${machine.state.id}${separator}) => ${machine.state.id};`;
    })
    .join("\n");
  const invariantPredicates = machine.invariants
    .map(
      (invariant) =>
        `export const ${invariant.id}Holds = (state: ${machine.state.id}): boolean =>\n  ${projectStatePredicate(invariant.proposition, "state")};`,
    )
    .join("\n\n");
  const validState = machine.invariants.map(({ id }) => `${id}Holds(state)`).join(" && ");

  const operations = [...machine.initializers, ...machine.transitions];
  const guards = operations
    .map((operation) => {
      const isTransition = machine.transitions.some(({ id }) => id === operation.id);
      const parameters = operation.parameters.map(({ id }) => `${id}: bigint`).join(", ");
      const stateParameter = isTransition ? `state: ${machine.state.id}` : "";
      const signature = [stateParameter, parameters].filter((part) => part.length > 0).join(", ");
      const requirements = [
        ...(isTransition ? [validState] : []),
        ...operation.requires.map((requirement) => projectStatePredicate(requirement, "state")),
      ].join(" && ");
      return `export const is${operation.id[0]?.toUpperCase() ?? ""}${operation.id.slice(1)}Enabled = (${signature}): boolean =>\n  ${requirements.length === 0 ? "true" : requirements};`;
    })
    .join("\n\n");

  const inputArbitraries = operations
    .map((operation) => {
      const isTransition = machine.transitions.some(({ id }) => id === operation.id);
      const entries = [
        ...(isTransition ? ["  state: ValidStateArbitrary,"] : []),
        ...operation.parameters.map(({ id }) => `  ${id}: IntegerArbitrary,`),
      ].join("\n");
      const inputNames = [
        ...(isTransition ? ["state"] : []),
        ...operation.parameters.map(({ id }) => id),
      ].join(", ");
      const arbitraryName = `${lowerFirst(operation.id)}InputArbitrary`;
      const guardName = `is${operation.id[0]?.toUpperCase() ?? ""}${operation.id.slice(1)}Enabled`;
      return `const ${arbitraryName} = FastCheck.record({\n${entries}\n}).filter(({ ${inputNames} }) => ${guardName}(${inputNames}));`;
    })
    .join("\n\n");

  const properties = operations
    .flatMap((operation) => {
      const isTransition = machine.transitions.some(({ id }) => id === operation.id);
      const inputNames = operation.parameters.map(({ id }) => `input.${id}`).join(", ");
      const callArguments = isTransition
        ? ["input.state", inputNames].filter((part) => part.length > 0).join(", ")
        : inputNames;
      return machine.invariants.map((invariant) => {
        const propertyName = `${lowerFirst(operation.id)}${invariant.id[0]?.toUpperCase() ?? ""}${invariant.id.slice(1)}Property`;
        return `const ${propertyName} = (realization: ${machine.id}StateMachineModel) =>\n  FastCheck.property(${lowerFirst(operation.id)}InputArbitrary, (input) =>\n    ${invariant.id}Holds(realization.${operation.id}(${callArguments})),\n  );`;
      });
    })
    .join("\n\n");

  const registrations = operations
    .flatMap((operation) => {
      const isTransition = machine.transitions.some(({ id }) => id === operation.id);
      const inputNames = operation.parameters.map(({ id }) => `input.${id}`).join(", ");
      const callArguments = isTransition
        ? ["input.state", inputNames].filter((part) => part.length > 0).join(", ")
        : inputNames;
      const relation = isTransition ? "preserves" : "establishes";
      return machine.invariants.map(
        (invariant) => `  it.effect.prop(
    "${machine.id}.${operation.id} ${relation} ${invariant.id}",
    [${lowerFirst(operation.id)}InputArbitrary] as const,
    ([input]) =>
      Effect.sync(() => {
        const next = realization.${operation.id}(${callArguments});
        expect(${invariant.id}Holds(next)).toBe(true);
      }),
    { fastCheck: { seed: options.seed, numRuns: options.numRuns } },
  );`,
      );
    })
    .join("\n\n");

  const checks = operations
    .flatMap((operation) =>
      machine.invariants.map((invariant) => {
        const details = `${lowerFirst(operation.id)}${invariant.id[0]?.toUpperCase() ?? ""}${invariant.id.slice(1)}Details`;
        const property = `${lowerFirst(operation.id)}${invariant.id[0]?.toUpperCase() ?? ""}${invariant.id.slice(1)}Property`;
        return `  const ${details} = FastCheck.check(${property}(realization), {
    seed: options.seed,
    numRuns: options.numRuns,
  });`;
      }),
    )
    .join("\n\n");

  const results = operations
    .flatMap((operation) => {
      const isTransition = machine.transitions.some(({ id }) => id === operation.id);
      const relation = isTransition ? "preserves" : "establishes";
      return machine.invariants.map((invariant) => {
        const details = `${lowerFirst(operation.id)}${invariant.id[0]?.toUpperCase() ?? ""}${invariant.id.slice(1)}Details`;
        return `    {
      obligation: "${machine.id}.${operation.id}.${relation}.${invariant.id}",
      operation: "${operation.id}",
      invariant: "${invariant.id}",
      passed: !${details}.failed,
      requestedCases: options.numRuns,
      executedRuns: ${details}.numRuns,
      numSkips: ${details}.numSkips,
      seed: ${details}.seed,
      numShrinks: ${details}.numShrinks,
      counterexamplePath: ${details}.counterexamplePath,
      counterexample:
        ${details}.counterexample === null
          ? null
          : ${details}.counterexample.map(stringifyCounterexample),
    },`;
      });
    })
    .join("\n");

  return `// Generated by BANG M004. Do not edit.\nimport { expect, it } from "@effect/vitest";\nimport { Effect, Schema } from "effect";\nimport { FastCheck } from "effect/testing";\n\nexport const ${machine.state.id} = Schema.Struct({\n${fields}\n});\nexport type ${machine.state.id} = typeof ${machine.state.id}.Type;\n\nexport interface ${machine.id}StateMachineModel {\n${modelInitializers}\n${modelTransitions}\n}\n\nexport interface StateMachineSuiteOptions {\n  readonly seed: number;\n  readonly numRuns: number;\n}\n\nexport interface StateMachineLawResult {\n  readonly obligation: string;\n  readonly operation: string;\n  readonly invariant: string;\n  readonly passed: boolean;\n  readonly requestedCases: number;\n  readonly executedRuns: number;\n  readonly numSkips: number;\n  readonly seed: number;\n  readonly numShrinks: number;\n  readonly counterexamplePath: string | null;\n  readonly counterexample: ReadonlyArray<string> | null;\n}\n\n${invariantPredicates}\n\n${guards}\n\nconst IntegerArbitrary = Schema.toArbitrary(Schema.BigInt)(FastCheck);\nconst StateArbitrary = Schema.toArbitrary(${machine.state.id})(FastCheck);\nconst ValidStateArbitrary = StateArbitrary.filter((state) => ${validState});\n\n${inputArbitraries}\n\n${properties}\n\nconst stringifyCounterexample = (value: unknown): string =>\n  JSON.stringify(value, (_key, nested) => typeof nested === "bigint" ? String(nested) : nested) ?? "undefined";\n\nexport const register${machine.id}StateMachineProperties = (\n  realization: ${machine.id}StateMachineModel,\n  options: StateMachineSuiteOptions,\n): void => {\n${registrations}\n};\n\nexport const check${machine.id}StateMachineProperties = (\n  realization: ${machine.id}StateMachineModel,\n  options: StateMachineSuiteOptions,\n): ReadonlyArray<StateMachineLawResult> => {\n${checks}\n\n  return [\n${results}\n  ];\n};\n`;
};

export const projectEffectService = (service: ServiceDeclaration): string => {
  const operations = service.operations
    .map((operation) => {
      const parameters = operation.parameters
        .map(({ id, type }) => `${id}: ${projectType(type)}`)
        .join(", ");
      return `  readonly ${operation.id}: (${parameters}) => Effect.Effect<${projectType(operation.result)}>;`;
    })
    .join("\n");

  return `// Generated by BANG M000. Do not edit.\nimport * as Context from "effect/Context";\nimport type * as Effect from "effect/Effect";\n\nexport interface ${service.id}Shape {\n${operations}\n}\n\nexport class ${service.id} extends Context.Service<${service.id}, ${service.id}Shape>()(\n  "@bang/${service.id}",\n) {}\n`;
};
