describe("M018 single-use capability projection", () => {
  test("emits a deterministic exact-one boundary and rejects unsupported quantities", async () => {
    const document = await checkedDocument();
    const unsupportedDocument = structuredClone(document);
    const source = Effect.runSync(
      projectEffectSingleUseOperationRealization(document, "WithdrawAccountOnce"),
    );
    const repeated = Effect.runSync(
      projectEffectSingleUseOperationRealization(document, "WithdrawAccountOnce"),
    );
    expect(source).toBe(repeated);
    expect(source).toContain("// Generated by BANG M018. Do not edit.");
    expect(source).toContain("export interface DebitAccountGrant");
    expect(source).toContain("export class DebitAccountGrantAlreadyConsumed");
    expect(source).toContain("export const makeDebitAccountLayer");
    expect(source).toContain("export const makeWithdrawAccountOnceLayer");
    expect(source).toContain("export const WithdrawAccountOnceObservation");
    expect(source).toContain('Schema.TaggedStruct("CapabilityUseRejected"');
    expect(source).toContain("Ref.modify");
    expect(source.indexOf("destination !== withdrawAccountOnceDestination")).toBeLessThan(
      source.indexOf("yield* consumeDebitAccountGrant"),
    );
    expect(source.indexOf("yield* consumeDebitAccountGrant")).toBeLessThan(
      source.indexOf("return yield* runImplementation"),
    );

    const realization = unsupportedDocument.declarations.find(
      (declaration) =>
        declaration.kind === "operationRealization" && declaration.id === "WithdrawAccountOnce",
    );
    if (realization === undefined || realization.kind !== "operationRealization") {
      throw new Error("WithdrawAccountOnce fixture is missing");
    }
    const requirement = realization.requires[0];
    if (requirement === undefined) throw new Error("WithdrawAccountOnce requirement is missing");
    Reflect.set(requirement, "quantity", { kind: "exactly", uses: "2" });
    const unsupported = Effect.runSync(
      Effect.flip(
        projectEffectSingleUseOperationRealization(unsupportedDocument, "WithdrawAccountOnce"),
      ),
    );
    expect(unsupported.reason).toBe("unsupported-target");
  });

  test("shares one safe symbol map across exact-one boundary and probe emission", async () => {
    const lowercaseDocument = structuredClone(await checkedDocument());
    const lowercaseRealization = lowercaseDocument.declarations.find(
      (declaration) =>
        declaration.kind === "operationRealization" && declaration.id === "WithdrawAccountOnce",
    );
    if (
      lowercaseRealization === undefined ||
      lowercaseRealization.kind !== "operationRealization"
    ) {
      throw new Error("WithdrawAccountOnce fixture is missing");
    }
    Reflect.set(lowercaseRealization, "id", "withdrawAccountOnce");
    const lowercase = Effect.runSync(
      projectEffectSingleUseOperationRealizationMaterials(lowercaseDocument, "withdrawAccountOnce"),
    );
    expect(lowercase.boundary).toContain("export class WithdrawAccountOnce");
    expect(lowercase.probe).toContain("WithdrawAccountOnce");

    const reservedDocument = structuredClone(await checkedDocument());
    const reservedMachine = reservedDocument.declarations.find(
      (declaration) => declaration.kind === "stateMachine" && declaration.id === "Account",
    );
    const reservedRealization = reservedDocument.declarations.find(
      (declaration) =>
        declaration.kind === "operationRealization" && declaration.id === "WithdrawAccountOnce",
    );
    if (
      reservedMachine === undefined ||
      reservedMachine.kind !== "stateMachine" ||
      reservedRealization === undefined ||
      reservedRealization.kind !== "operationRealization"
    ) {
      throw new Error("exact-one fixtures are missing");
    }
    Reflect.set(reservedMachine.transitions[0]!, "id", "class");
    Reflect.set(reservedRealization, "operation", {
      stateMachine: "Account",
      operation: "class",
    });
    const reserved = Effect.runSync(
      Effect.flip(
        projectEffectSingleUseOperationRealizationMaterials(
          reservedDocument,
          "WithdrawAccountOnce",
        ),
      ),
    );
    expect(reserved.reason).toBe("invalid-identifier");

    const collisionDocument = structuredClone(await checkedDocument());
    const collisionCapability = collisionDocument.declarations.find(
      (declaration) => declaration.kind === "capability" && declaration.id === "DebitAccount",
    );
    const collisionRealization = collisionDocument.declarations.find(
      (declaration) =>
        declaration.kind === "operationRealization" && declaration.id === "WithdrawAccountOnce",
    );
    if (
      collisionCapability === undefined ||
      collisionCapability.kind !== "capability" ||
      collisionRealization === undefined ||
      collisionRealization.kind !== "operationRealization"
    ) {
      throw new Error("exact-one fixtures are missing");
    }
    Reflect.set(collisionCapability, "id", "Layer");
    Reflect.set(collisionRealization.requires[0]!, "capability", "Layer");
    const collision = Effect.runSync(
      Effect.flip(
        projectEffectSingleUseOperationRealizationMaterials(
          collisionDocument,
          "WithdrawAccountOnce",
        ),
      ),
    );
    expect(collision.reason).toBe("identifier-collision");
  });

  test("consumes before execution, preserves failed grants, and serializes concurrent reuse", async () => {
    const implementation: WithdrawAccountOnceImplementation = {
      withdraw: (state, amount) => Effect.succeed({ balance: state.balance - amount }),
    };
    const boundary = Layer.mergeAll(
      makeDebitAccountLayer(),
      makeWithdrawAccountOnceLayer(implementation),
    );
    const result = await Effect.runPromise(
      Effect.gen(function* () {
        const issuer = yield* DebitAccount;
        const grant = yield* issuer.issueGrant;
        const first = yield* observeWithdrawAccountOnce(grant, "account-1", { balance: 10n }, 4n);
        const second = yield* observeWithdrawAccountOnce(grant, "account-1", first.state, 1n);
        const concurrentGrant = yield* issuer.issueGrant;
        const concurrent = yield* Effect.forEach(
          [0, 1],
          () => observeWithdrawAccountOnce(concurrentGrant, "account-1", { balance: 10n }, 4n),
          { concurrency: 2 },
        );
        return { first, second, concurrent };
      }).pipe(
        // Test registration is the conformance-harness composition root.
        // @effect-diagnostics-next-line strictEffectProvide:off
        Effect.provide(boundary),
      ),
    );
    expect(result.first).toMatchObject({
      _tag: "Success",
      state: { balance: 6n },
      remainingUses: 0,
      implementationCalls: 1,
    });
    expect(result.second).toMatchObject({
      _tag: "CapabilityUseRejected",
      failure: "DebitAccountGrantAlreadyConsumed",
      state: { balance: 6n },
      remainingUses: 0,
      implementationCalls: 1,
    });
    expect(result.concurrent.filter(({ _tag }) => _tag === "Success")).toHaveLength(1);
    expect(result.concurrent.filter(({ _tag }) => _tag === "CapabilityUseRejected")).toHaveLength(
      1,
    );
  });

  test("does not consume wrong destinations or disabled transitions", async () => {
    const implementation: WithdrawAccountOnceImplementation = {
      withdraw: (state, amount) => Effect.succeed({ balance: state.balance - amount }),
    };
    const boundary = Layer.mergeAll(
      makeDebitAccountLayer(),
      makeWithdrawAccountOnceLayer(implementation),
    );
    const result = await Effect.runPromise(
      Effect.gen(function* () {
        const issuer = yield* DebitAccount;
        const wrongGrant = yield* issuer.issueGrant;
        const wrong = yield* observeWithdrawAccountOnce(
          wrongGrant,
          "account-2",
          { balance: 10n },
          1n,
        );
        const wrongRemaining = yield* debitAccountGrantRemainingUses(wrongGrant);
        const disabledGrant = yield* issuer.issueGrant;
        const disabled = yield* observeWithdrawAccountOnce(
          disabledGrant,
          "account-1",
          { balance: 10n },
          11n,
        );
        const disabledRemaining = yield* debitAccountGrantRemainingUses(disabledGrant);
        return { wrong, wrongRemaining, disabled, disabledRemaining };
      }).pipe(
        // Test registration is the conformance-harness composition root.
        // @effect-diagnostics-next-line strictEffectProvide:off
        Effect.provide(boundary),
      ),
    );
    expect(result.wrong._tag).toBe("WrongDestination");
    expect(result.wrongRemaining).toBe(1);
    expect(result.disabled).toMatchObject({
      _tag: "DomainRejected",
      failure: "WithdrawalRejectedOnce",
      state: { balance: 10n },
      remainingUses: 1,
      implementationCalls: 0,
    });
    expect(result.disabledRemaining).toBe(1);
  });

  test("keeps a consumed grant consumed after an implementation defect", async () => {
    const implementation: WithdrawAccountOnceImplementation = {
      withdraw: () => Effect.die("controlled defect"),
    };
    const boundary = Layer.mergeAll(
      makeDebitAccountLayer(),
      makeWithdrawAccountOnceLayer(implementation),
    );
    const result = await Effect.runPromise(
      Effect.gen(function* () {
        const issuer = yield* DebitAccount;
        const grant = yield* issuer.issueGrant;
        const first = yield* observeWithdrawAccountOnce(grant, "account-1", { balance: 10n }, 4n);
        const reuse = yield* observeWithdrawAccountOnce(grant, "account-1", { balance: 10n }, 1n);
        return { first, reuse };
      }).pipe(
        // Test registration is the conformance-harness composition root.
        // @effect-diagnostics-next-line strictEffectProvide:off
        Effect.provide(boundary),
      ),
    );
    expect(result.first).toMatchObject({
      _tag: "Defect",
      failure: "implementation-defect",
      remainingUses: 0,
      implementationCalls: 1,
    });
    expect(result.reuse).toMatchObject({
      _tag: "CapabilityUseRejected",
      failure: "DebitAccountGrantAlreadyConsumed",
      remainingUses: 0,
      implementationCalls: 1,
    });
  });
});
