describe("M019 runtime data projection", () => {
  test("preserves the default projection bytes when no profile is supplied", async () => {
    const document = await checkedBridgeTermDocument();
    const defaultSource = Effect.runSync(projectEffectData(document, "BridgeTerm"));
    const explicitVitestSource = Effect.runSync(
      projectEffectData(document, "BridgeTerm", { profile: "vitest" }),
    );
    const repeatedSource = Effect.runSync(projectEffectData(document, "BridgeTerm"));

    expect(defaultSource).toBe(explicitVitestSource);
    expect(defaultSource).toBe(repeatedSource);
    expect(defaultSource).toContain("// Generated by BANG M005A. Do not edit.");
    expect(defaultSource).toContain('import { expect, it } from "@effect/vitest";');
    expect(defaultSource).toContain("registerBridgeTermDecoderConformance");
  });

  test("emits a standalone runtime conformance boundary", async () => {
    const document = await checkedBridgeTermDocument();
    const source = Effect.runSync(
      projectEffectData(document, "BridgeTerm", { profile: "runtime" }),
    );

    expect(source.startsWith("// Generated by BANG M019. Do not edit.\n")).toBe(true);
    expect(source).toContain("export const BridgeTerm: Schema.Codec<BridgeTerm>");
    expect(source).toContain("const BridgeTermReference = Schema.suspend");
    expect(source).toContain("export interface BridgeTermDecoder");
    expect(source).toContain("export interface DecoderPropertyResult");
    expect(source).toContain("readonly requestedCases: number");
    expect(source).toContain("readonly maximumObservedDepth: number");
    expect(source).toContain("const BridgeTermDomainPath");
    expect(source).toContain("BridgeTermDomainPath(validCounterexample)");
    expect(source).toContain("export const checkBridgeTermDecoder");
    expect(source).not.toContain("@effect/vitest");
    expect(source).not.toContain("it.effect");
    expect(source).not.toContain("expect(");
    expect(source).not.toContain("registerBridgeTermDecoderConformance");
  });
});

